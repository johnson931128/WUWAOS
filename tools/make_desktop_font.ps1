[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$FontPath,
    [string]$OutputPath = (Join-Path $PSScriptRoot '../kernel/font_terminal.h')
)

# Windows-only asset generation; normal OS builds use the checked-in header.
# Source: microsoft/cascadia-code v2407.24, ttf/static/CascadiaMono-Regular.ttf.
# The rasterized subset is named WUWAOS Terminal; see licenses/Cascadia-OFL.txt.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$collection = [Drawing.Text.PrivateFontCollection]::new()
$bitmap = $null
$graphics = $null
$font = $null
$format = $null
try {
    $collection.AddFontFile((Resolve-Path -LiteralPath $FontPath).Path)
    if ($collection.Families[0].Name -ne 'Cascadia Mono') {
        throw 'Expected Cascadia Mono Regular from the official v2407.24 release.'
    }
    $font = [Drawing.Font]::new($collection.Families[0], 13, [Drawing.FontStyle]::Regular, [Drawing.GraphicsUnit]::Pixel)
    # Render with spare space so an oversized glyph fails instead of being clipped.
    $bitmap = [Drawing.Bitmap]::new(16, 24)
    $graphics = [Drawing.Graphics]::FromImage($bitmap)
    $graphics.TextRenderingHint = [Drawing.Text.TextRenderingHint]::AntiAliasGridFit
    $format = [Drawing.StringFormat]::GenericTypographic.Clone()
    $format.FormatFlags = $format.FormatFlags -bor [Drawing.StringFormatFlags]::NoWrap
    $format.Trimming = [Drawing.StringTrimming]::None
    $lines = [Collections.Generic.List[string]]::new()
    $lines.Add('/* WUWAOS Terminal: rasterized ASCII subset of Cascadia Mono Regular v2407.24.')
    $lines.Add(' * SIL Open Font License 1.1: licenses/Cascadia-OFL.txt.')
    $lines.Add(' * Generated by tools/make_desktop_font.ps1; 8x16, two 4-bit coverage samples per byte.')
    $lines.Add(' * High nibble is the left pixel. This subset is renamed under the OFL. */')
    $lines.Add('#ifndef WUWAOS_FONT_TERMINAL_H')
    $lines.Add('#define WUWAOS_FONT_TERMINAL_H')
    $lines.Add('#include <stdint.h>')
    $lines.Add('#define TERMINAL_FONT_WIDTH 8U')
    $lines.Add('#define TERMINAL_FONT_HEIGHT 16U')
    $lines.Add('static const uint8_t terminal_font[95][64] = {')
    for ($code = 32; $code -le 126; $code++) {
        $graphics.Clear([Drawing.Color]::Black)
        $graphics.DrawString(([char]$code).ToString(), $font, [Drawing.Brushes]::White, [Drawing.PointF]::new(0, 0), $format)
        for ($y = 0; $y -lt 24; $y++) {
            for ($x = 0; $x -lt 16; $x++) {
                if (($x -ge 8 -or $y -ge 16) -and $bitmap.GetPixel($x, $y).R -ge 9) {
                    throw ('Glyph U+{0:X4} exceeds the 8x16 cell.' -f $code)
                }
            }
        }
        $values = [Collections.Generic.List[string]]::new()
        for ($y = 0; $y -lt 16; $y++) {
            for ($x = 0; $x -lt 8; $x += 2) {
                $left = [int][Math]::Floor(($bitmap.GetPixel($x, $y).R * 15 + 127) / 255)
                $right = [int][Math]::Floor(($bitmap.GetPixel($x + 1, $y).R * 15 + 127) / 255)
                $values.Add(('0x{0:x2}' -f (($left -shl 4) -bor $right)))
            }
        }
        $lines.Add(('    {{ {0} }}, /* U+{1:X4} */' -f ($values -join ', '), $code))
    }
    $lines.Add('};')
    $lines.Add('#endif')
    [IO.File]::WriteAllText([IO.Path]::GetFullPath($OutputPath), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
} finally {
    if ($format) { $format.Dispose() }
    if ($graphics) { $graphics.Dispose() }
    if ($bitmap) { $bitmap.Dispose() }
    if ($font) { $font.Dispose() }
    $collection.Dispose()
}
